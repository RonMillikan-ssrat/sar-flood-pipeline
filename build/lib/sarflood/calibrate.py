"""Sentinel-1 GRD thermal-noise removal and radiometric calibration, from the LUT XMLs.

    sigma0 = (DN^2 - noise) / A^2

    A      = sigmaNought from annotation/calibration/calibration-*.xml, a sparse grid
             (vectors at given lines, values at given pixels) interpolated to every pixel
    noise  = noiseRangeLut (sparse grid, interpolated the same way)
             x noiseAzimuthLut (per sub-swath blocks, interpolated along lines within each block)
             from annotation/calibration/noise-*.xml

Interpolation: each vector is interpolated along range to the output columns,
then the stack is interpolated along azimuth (lines) to the output rows. This
handles vectors whose pixel positions differ from line to line.

Output stays in radar geometry (rows = azimuth lines, cols = range samples) with
the product's GCPs copied, so it can be compared pixel for pixel with SNAP's
Calibration output before any terrain correction.

Reference: ESA, "Thermal Denoising of Products Generated by the S-1 IPF" (2017),
and the LUT structure as found in the product annotation.
"""

from __future__ import annotations

import logging
import warnings
import xml.etree.ElementTree as ET
import zipfile
from dataclasses import dataclass
from pathlib import Path

import numpy as np

log = logging.getLogger(__name__)


# Intensity (DN^2 units) that SNAP 14's ThermalNoiseRemoval substitutes where
# noise removal leaves intensity <= 0 with clipNegativeValues=true.
SNAP_INTENSITY_FLOOR = 1e-5


def _floats(e: ET.Element) -> np.ndarray:
    return np.array(e.text.split(), dtype=np.float64)


@dataclass
class SparseGrid:
    """Values given at (line, pixels) for a set of vectors."""
    lines: np.ndarray            # (n,)
    pixels: list[np.ndarray]     # n arrays (lengths may differ)
    values: list[np.ndarray]

    def sample(self, rows: np.ndarray, cols: np.ndarray) -> np.ndarray:
        # 1) along range, per vector -> (n, ncols)
        across = np.stack([np.interp(cols, p, v) for p, v in zip(self.pixels, self.values)])
        # 2) along azimuth -> (nrows, ncols). Every column shares the same vector
        #    lines, so compute bracketing indices and weights once per row, then
        #    blend whole rows. Clamped beyond the ends, like np.interp.
        if self.lines.size == 1:
            return np.broadcast_to(across[0], (rows.size, cols.size)).copy()
        r = np.clip(rows, self.lines[0], self.lines[-1])
        i1 = np.clip(np.searchsorted(self.lines, r, side="right"), 1, self.lines.size - 1)
        i0 = i1 - 1
        w = (r - self.lines[i0]) / (self.lines[i1] - self.lines[i0])
        return across[i0] * (1 - w)[:, None] + across[i1] * w[:, None]


@dataclass
class AzimuthBlock:
    swath: str
    first_line: int
    last_line: int
    first_sample: int
    last_sample: int
    lines: np.ndarray
    lut: np.ndarray


def parse_calibration(xml: bytes, lut: str = "sigmaNought") -> SparseGrid:
    root = ET.fromstring(xml)
    const = float(root.findtext("calibrationInformation/absoluteCalibrationConstant", "1"))
    vecs = root.findall("calibrationVectorList/calibrationVector")
    if not vecs:
        raise ValueError("no calibrationVector elements")
    return SparseGrid(
        lines=np.array([int(v.findtext("line")) for v in vecs], dtype=np.float64),
        pixels=[_floats(v.find("pixel")) for v in vecs],
        # ESA convention: the LUT value is divided by the absolute constant (1.0 for S1)
        values=[_floats(v.find(lut)) / const for v in vecs],
    )


def parse_noise(xml: bytes) -> tuple[SparseGrid, list[AzimuthBlock]]:
    root = ET.fromstring(xml)
    rvecs = root.findall("noiseRangeVectorList/noiseRangeVector")
    if not rvecs:  # pre-2018 products (IPF < 2.9) used a single noiseVector list
        raise ValueError("no noiseRangeVector elements (old IPF format not supported yet)")
    rng = SparseGrid(
        lines=np.array([int(v.findtext("line")) for v in rvecs], dtype=np.float64),
        pixels=[_floats(v.find("pixel")) for v in rvecs],
        values=[_floats(v.find("noiseRangeLut")) for v in rvecs],
    )
    blocks = [
        AzimuthBlock(
            swath=b.findtext("swath"),
            first_line=int(b.findtext("firstAzimuthLine")),
            last_line=int(b.findtext("lastAzimuthLine")),
            first_sample=int(b.findtext("firstRangeSample")),
            last_sample=int(b.findtext("lastRangeSample")),
            lines=_floats(b.find("line")),
            lut=_floats(b.find("noiseAzimuthLut")),
        )
        for b in root.findall("noiseAzimuthVectorList/noiseAzimuthVector")
    ]
    return rng, blocks


def azimuth_noise(blocks: list[AzimuthBlock], rows: np.ndarray, cols: np.ndarray) -> np.ndarray:
    """Azimuth noise factor for a window. Pixels outside every block get 1.0."""
    out = np.ones((rows.size, cols.size), dtype=np.float64)
    for b in blocks:
        rmask = (rows >= b.first_line) & (rows <= b.last_line)
        cmask = (cols >= b.first_sample) & (cols <= b.last_sample)
        if not rmask.any() or not cmask.any():
            continue
        prof = np.interp(rows[rmask], b.lines, b.lut)  # (nr,)
        out[np.ix_(rmask, cmask)] = prof[:, None]
    return out


@dataclass
class BlockStats:
    valid: int = 0       # DN > 0
    negative: int = 0    # DN^2 - noise <= 0 (set to the floor when clipping is on)

    def add(self, other: BlockStats) -> None:
        self.valid += other.valid
        self.negative += other.negative


def sigma0_block(dn: np.ndarray, rows: np.ndarray, cols: np.ndarray, cal: SparseGrid,
                 noise: tuple[SparseGrid, list[AzimuthBlock]] | None,
                 clip_negative: bool = True,
                 clip_floor: float = SNAP_INTENSITY_FLOOR) -> tuple[np.ndarray, BlockStats]:
    """clip_negative=True: where noise removal leaves intensity (DN^2 - noise) <= 0,
    set it to `clip_floor` before calibrating, as SNAP 14 does. Verified on
    S1A 2022-08-30 track 78: SNAP's sigma0 x A^2 = 1e-5 at every such pixel.

    clip_negative=False keeps negative power. Use that when the data will be
    averaged or resampled later (terrain correction, speckle filtering), since
    clipping first biases dark targets such as water upward (MPC-0392)."""
    power = dn.astype(np.float64) ** 2
    if noise is not None:
        rng, blocks = noise
        power -= rng.sample(rows, cols) * azimuth_noise(blocks, rows, cols)
    nodata = dn == 0
    neg = (power <= 0) & ~nodata
    if clip_negative:
        power[neg] = clip_floor
    a = cal.sample(rows, cols)
    s0 = power / (a * a)
    s0[nodata] = np.nan
    return s0.astype(np.float32), BlockStats(valid=int((~nodata).sum()), negative=int(neg.sum()))


@dataclass
class SafeMembers:
    measurement: str
    calibration: str
    noise: str


def find_members(zf: zipfile.ZipFile, pol: str) -> SafeMembers:
    pol = pol.lower()

    def one(pred) -> str:
        hits = [n for n in zf.namelist() if pred(n)]
        if len(hits) != 1:
            raise ValueError(f"expected 1 match for {pol}, got {hits}")
        return hits[0]

    return SafeMembers(
        measurement=one(lambda n: "/measurement/" in n and f"-{pol}-" in n and n.endswith(".tiff")),
        calibration=one(lambda n: "/calibration/calibration-" in n and f"-{pol}-" in n),
        noise=one(lambda n: "/calibration/noise-" in n and f"-{pol}-" in n),
    )


def calibrate_safe(zip_path: Path | str, pol: str, out_path: Path | str,
                   window: tuple[int, int, int, int] | None = None,
                   remove_noise: bool = True, clip_negative: bool = True,
                   block_rows: int = 512) -> BlockStats:
    """Write sigma0 (linear, float32) for one polarisation to a GeoTIFF in radar geometry.

    window = (row0, row1, col0, col1), half-open, for quick tests on a subset.
    """
    import rasterio
    from rasterio.control import GroundControlPoint
    from rasterio.errors import NotGeoreferencedWarning
    from rasterio.windows import Window

    zip_path = Path(zip_path)
    with zipfile.ZipFile(zip_path) as zf:
        m = find_members(zf, pol)
        cal = parse_calibration(zf.read(m.calibration))
        noise = parse_noise(zf.read(m.noise)) if remove_noise else None

    stats = BlockStats()
    with rasterio.open(f"/vsizip/{zip_path}/{m.measurement}") as src:
        r0, r1, c0, c1 = window or (0, src.height, 0, src.width)
        if not (0 <= r0 < r1 <= src.height and 0 <= c0 < c1 <= src.width):
            raise ValueError(f"window {window} outside image {src.height}x{src.width}")
        gcps, crs = src.gcps
        # Shift GCPs into the window's pixel frame so the subset still geolocates.
        gcps = [GroundControlPoint(row=g.row - r0, col=g.col - c0, x=g.x, y=g.y, z=g.z)
                for g in gcps]
        profile = {
            "driver": "GTiff", "dtype": "float32", "count": 1,
            "width": c1 - c0, "height": r1 - r0, "nodata": float("nan"),
            "tiled": True, "blockxsize": 512, "blockysize": 512,
            "compress": "deflate", "predictor": 3, "BIGTIFF": "IF_SAFER",
        }
        cols = np.arange(c0, c1, dtype=np.float64)
        out_path = Path(out_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        # The new file has no georeferencing until the GCPs are assigned on the next
        # line, which makes rasterio warn on open. Expected here, so silenced.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", NotGeoreferencedWarning)
            dst = rasterio.open(out_path, "w", **profile)
        with dst:
            dst.gcps = (gcps, crs)
            for top in range(r0, r1, block_rows):
                bottom = min(top + block_rows, r1)
                dn = src.read(1, window=Window(c0, top, c1 - c0, bottom - top))
                rows = np.arange(top, bottom, dtype=np.float64)
                s0, st = sigma0_block(dn, rows, cols, cal, noise, clip_negative)
                stats.add(st)
                dst.write(s0, 1, window=Window(0, top - r0, c1 - c0, bottom - top))
            dst.update_tags(source=zip_path.name, polarisation=pol.upper(),
                            quantity="sigma0_linear", noise_removed=str(remove_noise),
                            negatives_clipped=str(clip_negative),
                            window=f"{r0}:{r1},{c0}:{c1}")
    log.info("%s %s: %d valid px, %d negative (%.2f%%)", zip_path.name, pol,
             stats.valid, stats.negative, 100 * stats.negative / max(stats.valid, 1))
    return stats
